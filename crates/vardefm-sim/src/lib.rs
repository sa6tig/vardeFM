//! FM radio channel simulator.
//!
//! Models what happens to modem audio between two FM radios:
//! TX audio filtering, pre-emphasis, deviation limiting, the FM modulator, RF noise,
//! the IF filter, the discriminator (including threshold "clicks" at low signal),
//! de-emphasis, RX audio filtering, squelch, TX key-up delay, and sound-card clock offset.
//! Optionally, Rayleigh or Rician flat fading ("picket fencing" on a mobile or
//! portable path) is applied to the carrier before the noise and the IF filter.

use num_complex::Complex32;
use rand::rngs::StdRng;
use rand::{Rng, SeedableRng};
use rand_distr::{Distribution, Normal};
use std::f32::consts::PI;
use std::fmt;
use std::str::FromStr;
use vardefm_dsp::filter::{design_lowpass_fir, fir_complex, resample_cubic, Chain, FirstOrder};

/// Flat fading of the RF carrier: a moving station sees the sum of many reflections
/// whose Doppler shifts spread up to `doppler_hz`.
///
/// The complex gain has unit mean power, so `FmChannelConfig::cnr_db` is the mean CNR.
/// It is generated by a sum of sinusoids (Zheng and Xiao's model, Clarke/Jakes
/// spectrum), with phases drawn from the channel seed.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Fading {
    /// Maximum Doppler shift in Hz (speed / wavelength: 50 km/h on 2 m is about 7 Hz,
    /// 100 km/h on 70 cm about 40 Hz).
    pub doppler_hz: f32,
    /// Rician K-factor: power of the direct path over the scattered power, linear.
    /// 0 = Rayleigh (no direct path).
    pub k_factor: f32,
}

/// Sinusoids per quadrature component of the scattered part.
const FADING_SINUSOIDS: usize = 16;

impl Fading {
    pub fn rayleigh(doppler_hz: f32) -> Self {
        Self { doppler_hz, k_factor: 0.0 }
    }

    /// `k_db`: K-factor in dB.
    pub fn rician(doppler_hz: f32, k_db: f32) -> Self {
        Self { doppler_hz, k_factor: 10f32.powf(k_db / 10.0) }
    }

    /// Complex gain for `n` samples at `fs`, seeded by `seed`.
    pub fn gains(&self, fs: f32, n: usize, seed: u64) -> Vec<Complex32> {
        // Its own generator, so the noise samples do not change when fading is enabled.
        let mut rng = StdRng::seed_from_u64(seed ^ 0xFAD1_9000_0000_0001);
        let mut uniform = |scale: f64| rng.gen::<f64>() * scale;
        let tau = 2.0 * std::f64::consts::PI;
        let wd = tau * self.doppler_hz as f64 / fs as f64;
        let theta = uniform(tau) - std::f64::consts::PI;
        // (frequency in rad/sample, phase) for each sinusoid of the I and Q parts.
        let mut comps = Vec::with_capacity(2 * FADING_SINUSOIDS);
        for m in 1..=FADING_SINUSOIDS {
            let alpha = (tau * m as f64 - std::f64::consts::PI + theta) / (4 * FADING_SINUSOIDS) as f64;
            comps.push((wd * alpha.cos(), uniform(tau)));
            comps.push((wd * alpha.sin(), uniform(tau)));
        }
        let k = self.k_factor.max(0.0) as f64;
        let scatter = (1.0 / (FADING_SINUSOIDS as f64 * (k + 1.0))).sqrt();
        let los = (k / (k + 1.0)).sqrt();
        let (los_w, los_phase) = (wd * uniform(tau).cos(), uniform(tau));
        (0..n)
            .map(|i| {
                let t = i as f64;
                let (mut re, mut im) = (0.0, 0.0);
                for pair in comps.chunks(2) {
                    re += (pair[0].0 * t + pair[0].1).cos();
                    im += (pair[1].0 * t + pair[1].1).cos();
                }
                let (s, c) = (los_w * t + los_phase).sin_cos();
                Complex32::new((scatter * re + los * c) as f32, (scatter * im + los * s) as f32)
            })
            .collect()
    }
}

impl fmt::Display for Fading {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.k_factor <= 0.0 {
            write!(f, "rayleigh:{}", self.doppler_hz)
        } else {
            write!(f, "rician:{}:{}", self.doppler_hz, 10.0 * self.k_factor.log10())
        }
    }
}

/// `rayleigh:<doppler Hz>` or `rician:<doppler Hz>:<K dB>`.
impl FromStr for Fading {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, String> {
        let parts: Vec<&str> = s.split(':').collect();
        let num = |p: &str| p.parse::<f32>().map_err(|e| format!("bad number {p:?} in fading spec: {e}"));
        let fading = match parts.as_slice() {
            ["rayleigh", d] => Self::rayleigh(num(d)?),
            ["rician", d, k] => Self::rician(num(d)?, num(k)?),
            _ => return Err("fading must be rayleigh:<doppler Hz> or rician:<doppler Hz>:<K dB>".into()),
        };
        if !(fading.doppler_hz.is_finite() && fading.doppler_hz >= 0.0 && fading.k_factor.is_finite()) {
            return Err("fading Doppler must be >= 0 and K finite".into());
        }
        Ok(fading)
    }
}

#[derive(Clone, Debug)]
pub struct FmChannelConfig {
    pub fs: f32,
    /// Peak deviation in Hz for audio amplitude 1.0.
    pub deviation_hz: f32,
    /// Pre-/de-emphasis time constant in microseconds (None for the flat data port).
    pub emphasis_us: Option<f32>,
    /// TX audio passband in Hz.
    pub tx_band: (f32, f32),
    /// RX audio passband in Hz.
    pub rx_band: (f32, f32),
    /// IF filter bandwidth in Hz (two-sided).
    pub if_bandwidth_hz: f32,
    /// Carrier-to-noise ratio in the IF bandwidth, dB. None = no noise.
    pub cnr_db: Option<f32>,
    /// Flat fading of the carrier (None = static channel). `cnr_db` is then the mean CNR.
    pub fading: Option<Fading>,
    /// Deviation limiter: audio is clipped at this level after pre-emphasis.
    pub clip_level: f32,
    /// Time from PTT until the carrier is up and the receiver unsquelches.
    pub keyup_delay_s: f32,
    /// Noise burst heard after the carrier drops.
    pub squelch_tail_s: f32,
    /// Receiver clock error relative to the transmitter, in ppm.
    pub clock_offset_ppm: f32,
    pub lead_silence_s: f32,
    pub trail_silence_s: f32,
    pub seed: u64,
}

impl FmChannelConfig {
    /// Mic/speaker path of a typical 12.5 kHz FM voice radio.
    pub fn narrow() -> Self {
        Self {
            fs: 48_000.0,
            deviation_hz: 2_500.0,
            emphasis_us: Some(750.0),
            tx_band: (300.0, 3_000.0),
            rx_band: (300.0, 3_000.0),
            if_bandwidth_hz: 11_000.0,
            cnr_db: None,
            fading: None,
            clip_level: 1.0,
            keyup_delay_s: 0.05,
            squelch_tail_s: 0.1,
            clock_offset_ppm: 0.0,
            lead_silence_s: 0.2,
            trail_silence_s: 0.2,
            seed: 1,
        }
    }

    /// Flat 9600-baud data port path.
    pub fn wide() -> Self {
        Self {
            emphasis_us: None,
            deviation_hz: 3_000.0,
            tx_band: (20.0, 7_000.0),
            rx_band: (20.0, 7_000.0),
            if_bandwidth_hz: 16_000.0,
            ..Self::narrow()
        }
    }

    pub fn by_name(name: &str) -> Option<Self> {
        match name {
            "narrow" => Some(Self::narrow()),
            "wide" => Some(Self::wide()),
            _ => None,
        }
    }
}

/// Pass one transmission (audio at `cfg.fs`, full scale = peak deviation) through the channel.
pub fn transmit(cfg: &FmChannelConfig, audio: &[f32]) -> Vec<f32> {
    let fs = cfg.fs;
    let lead = (cfg.lead_silence_s * fs) as usize;
    let trail = (cfg.trail_silence_s * fs) as usize;
    let keyup = (cfg.keyup_delay_s * fs) as usize;
    let tail = (cfg.squelch_tail_s * fs) as usize;
    let total = lead + audio.len() + trail;
    let carrier = lead..lead + audio.len();

    // --- Transmitter audio chain ---
    let mut tx_chain = Chain::bandpass4(fs, cfg.tx_band.0, cfg.tx_band.1);
    let mut pre = cfg.emphasis_us.map(|us| FirstOrder::preemphasis(fs, us * 1e-6));
    let mut tx_audio = vec![0f32; total];
    for (i, &x) in audio.iter().enumerate() {
        let mut v = x;
        if let Some(p) = &mut pre {
            v = p.process(v);
        }
        v = v.clamp(-cfg.clip_level, cfg.clip_level);
        tx_audio[lead + i] = tx_chain.process(v);
    }

    // --- FM modulator, fading, RF noise ---
    let mut rng = StdRng::seed_from_u64(cfg.seed);
    let sigma = cfg.cnr_db.map(|c| (10f32.powf(-c / 10.0) * fs / cfg.if_bandwidth_hz / 2.0).sqrt());
    let normal = Normal::new(0.0f32, 1.0).unwrap();
    let mut phase = 0f32;
    let k = 2.0 * PI * cfg.deviation_hz / fs;
    let fade = cfg.fading.map(|f| f.gains(fs, total, cfg.seed));
    let rf: Vec<Complex32> = (0..total)
        .map(|i| {
            let mut z = if carrier.contains(&i) {
                phase = (phase + k * tx_audio[i]) % (2.0 * PI);
                let z = Complex32::from_polar(1.0, phase);
                fade.as_ref().map_or(z, |g| z * g[i])
            } else {
                Complex32::new(0.0, 0.0)
            };
            if let Some(s) = sigma {
                z += Complex32::new(normal.sample(&mut rng), normal.sample(&mut rng)) * s;
            } else if !carrier.contains(&i) {
                // A tiny noise floor keeps the discriminator defined with no carrier.
                z += Complex32::new(normal.sample(&mut rng), normal.sample(&mut rng)) * 1e-3;
            }
            z
        })
        .collect();

    // --- Receiver: IF filter, discriminator, de-emphasis, audio filter ---
    let taps = design_lowpass_fir(129, cfg.if_bandwidth_hz / 2.0, fs);
    let delay = taps.len() / 2;
    let iff = fir_complex(&taps, &rf);
    let mut de = cfg.emphasis_us.map(|us| FirstOrder::deemphasis(fs, us * 1e-6));
    let mut rx_chain = Chain::bandpass4(fs, cfg.rx_band.0, cfg.rx_band.1);
    let scale = fs / (2.0 * PI * cfg.deviation_hz);
    let mut out = vec![0f32; total];
    let mut prev = Complex32::new(1.0, 0.0);
    for i in 0..total {
        let z = iff[(i + delay).min(total - 1)];
        let mut v = (z * prev.conj()).arg() * scale;
        prev = z;
        if let Some(d) = &mut de {
            v = d.process(v);
        }
        out[i] = rx_chain.process(v);
    }

    // --- Squelch: closed until the carrier is up, open for a short tail afterwards ---
    let open = carrier.start + keyup..carrier.end + tail;
    for (i, v) in out.iter_mut().enumerate() {
        if !open.contains(&i) {
            *v = 0.0;
        }
    }

    if cfg.clock_offset_ppm != 0.0 {
        out = resample_cubic(&out, 1.0 + cfg.clock_offset_ppm as f64 * 1e-6);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn clean_tone_passes_through() {
        let cfg = FmChannelConfig { lead_silence_s: 0.0, keyup_delay_s: 0.0, ..FmChannelConfig::narrow() };
        let tone: Vec<f32> = (0..48_000).map(|i| 0.3 * (2.0 * PI * 1000.0 * i as f32 / 48_000.0).sin()).collect();
        let out = transmit(&cfg, &tone);
        let peak = out[24_000..40_000].iter().fold(0f32, |m, v| m.max(v.abs()));
        assert!((peak - 0.3).abs() < 0.05, "peak {peak}");
    }

    /// Mean power and the fraction of time more than 10 dB below it.
    fn fade_stats(f: Fading, seeds: std::ops::Range<u64>) -> (f32, f32) {
        let (mut power, mut deep, mut n) = (0.0, 0, 0);
        for seed in seeds {
            for g in f.gains(48_000.0, 480_000, seed) {
                let p = g.norm_sqr();
                power += p;
                deep += (p < 0.1) as usize;
                n += 1;
            }
        }
        (power / n as f32, deep as f32 / n as f32)
    }

    #[test]
    fn rayleigh_fading_statistics() {
        // 10 s at 20 Hz: 200 Doppler periods per seed.
        let (power, deep) = fade_stats(Fading::rayleigh(20.0), 0..8);
        assert!((power - 1.0).abs() < 0.1, "mean power {power}");
        // Rayleigh: P(|g|^2 < 0.1) = 1 - exp(-0.1) = 9.5%.
        assert!((deep - 0.095).abs() < 0.02, "deep fades {deep}");

        // A strong direct path (K = 10 dB) almost never fades 10 dB.
        let (power, deep) = fade_stats(Fading::rician(20.0, 10.0), 0..8);
        assert!((power - 1.0).abs() < 0.1, "mean power {power}");
        assert!(deep < 0.01, "deep fades {deep}");
    }

    #[test]
    fn fading_rate_follows_doppler() {
        // Rayleigh level crossing rate at the mean power: sqrt(2 pi) * fd * e^-1 ~= 0.92 fd.
        for fd in [5.0, 80.0] {
            let mut ups = 0;
            for seed in 0..8 {
                let g = Fading::rayleigh(fd).gains(48_000.0, 480_000, seed);
                ups += g.windows(2).filter(|w| w[0].norm_sqr() < 1.0 && w[1].norm_sqr() >= 1.0).count();
            }
            let rate = ups as f32 / 80.0;
            assert!((rate / (0.92 * fd) - 1.0).abs() < 0.2, "fd {fd}: {rate} crossings/s");
        }
    }

    #[test]
    fn fading_is_seeded_and_keeps_noise() {
        let tone: Vec<f32> = (0..48_000).map(|i| 0.3 * (2.0 * PI * 1000.0 * i as f32 / 48_000.0).sin()).collect();
        let cfg =
            FmChannelConfig { cnr_db: Some(15.0), fading: Some(Fading::rayleigh(20.0)), ..FmChannelConfig::narrow() };
        assert_eq!(transmit(&cfg, &tone), transmit(&cfg, &tone));
        assert_ne!(transmit(&cfg, &tone), transmit(&FmChannelConfig { seed: 2, ..cfg.clone() }, &tone));
        // Zero Doppler with K = infinity-ish is a static channel with a phase offset.
        let still = FmChannelConfig { cnr_db: None, fading: Some(Fading::rician(0.0, 60.0)), ..cfg.clone() };
        let plain = FmChannelConfig { cnr_db: None, fading: None, ..cfg };
        let (a, b) = (transmit(&still, &tone), transmit(&plain, &tone));
        // Away from the carrier onset, where the phase step makes a different click.
        let (a, b) = (&a[24_000..48_000], &b[24_000..48_000]);
        let err = a.iter().zip(b).map(|(x, y)| (x - y).powi(2)).sum::<f32>() / b.iter().map(|y| y * y).sum::<f32>();
        assert!(err < 1e-3, "relative error {err}");
    }

    #[test]
    fn fading_spec_parses() {
        assert_eq!("rayleigh:20".parse::<Fading>(), Ok(Fading::rayleigh(20.0)));
        let f: Fading = "rician:5:6".parse().unwrap();
        assert!((f.k_factor - 3.98).abs() < 0.01);
        assert_eq!(f.to_string().parse::<Fading>().map(|g| (g.k_factor - f.k_factor).abs() < 1e-4), Ok(true));
        assert!("rayleigh".parse::<Fading>().is_err());
        assert!("rician:5".parse::<Fading>().is_err());
        assert!("rayleigh:-1".parse::<Fading>().is_err());
    }
}

#[cfg(test)]
mod probe {
    use super::*;
    #[test]
    #[ignore]
    fn tone_snr_probe() {
        for (name, base) in [("narrow", FmChannelConfig::narrow()), ("wide", FmChannelConfig::wide())] {
            for cnr in [None, Some(30.0), Some(20.0), Some(12.0)] {
                let cfg = FmChannelConfig { cnr_db: cnr, lead_silence_s: 0.0, keyup_delay_s: 0.0, ..base.clone() };
                let n = 96_000;
                let tone: Vec<f32> = (0..n).map(|i| 0.35 * (2.0 * PI * 1000.0 * i as f32 / 48_000.0).sin()).collect();
                let out = transmit(&cfg, &tone);
                // least-squares fit of a 1 kHz sine, residual = noise+distortion
                let seg = 24_000..90_000;
                let (mut ss, mut cc, mut sc) = (0f64, 0f64, 0f64);
                let (mut ys, mut yc) = (0f64, 0f64);
                for i in seg.clone() {
                    let w = 2.0 * std::f64::consts::PI * 1000.0 * i as f64 / 48_000.0;
                    let (s, c) = w.sin_cos();
                    ss += s * s;
                    cc += c * c;
                    sc += s * c;
                    ys += out[i] as f64 * s;
                    yc += out[i] as f64 * c;
                }
                let det = ss * cc - sc * sc;
                let a = (ys * cc - yc * sc) / det;
                let b = (yc * ss - ys * sc) / det;
                let (mut sig, mut err) = (0f64, 0f64);
                for i in seg {
                    let w = 2.0 * std::f64::consts::PI * 1000.0 * i as f64 / 48_000.0;
                    let fit = a * w.sin() + b * w.cos();
                    sig += fit * fit;
                    err += (out[i] as f64 - fit).powi(2);
                }
                println!("{name} cnr={cnr:?}: SNR {:.1} dB", 10.0 * (sig / err).log10());
            }
        }
    }
}
